#!/usr/bin/env python3
"""Reproducible generator of the paper's numeric macros from the real test data.
Reads results_final/ (cyclic rows + calibration) and data/midband_stats.json,
computes every reported number deterministically (seeded bootstrap), and writes
results_macros.tex into the PAPER directory (the paper itself is NOT in this repo).
Run: python build/gen_macros.py
"""
import json
import random
from pathlib import Path
from collections import defaultdict

HERE = Path(__file__).resolve().parent           # artifact/v2/build
V2 = HERE.parent                                  # artifact/v2
R = V2/"results_final"
PAPER = V2.parent.parent                          # papers/culturaquant
OUT = PAPER/"results_macros.tex"

MODELS = ["Qwen__Qwen2.5-7B-Instruct","mistralai__Mistral-7B-Instruct-v0.3","microsoft__Phi-3.5-mini-instruct"]
SHORT  = {"Qwen__Qwen2.5-7B-Instruct":"Qwen","mistralai__Mistral-7B-Instruct-v0.3":"Mistral","microsoft__Phi-3.5-mini-instruct":"Phi"}
PREC = ["fp16","int8","nf4"]
SEED = 20260609
B = 5000

def load(setdir, model, prec):
    p = R/setdir/f"cyclic__{model}__{prec}.jsonl"
    rows=[]
    for ln in p.read_text(encoding="utf-8").splitlines():
        if not ln.strip(): continue
        d=json.loads(ln)
        if d.get("_summary"): continue
        rows.append(d)
    return rows

def acc(rows): return sum(r["correct"] for r in rows)/len(rows)
def rstd(rows):
    c=[0]*5
    for r in rows: c[r["pred"]]+=1
    n=sum(c); p=[x/n for x in c]; m=0.2
    return (sum((x-m)**2 for x in p)/5)**0.5
def by_item(rows):
    m=defaultdict(lambda:[0,0])
    for r in rows: m[r["id"]][0]+=r["correct"]; m[r["id"]][1]+=1
    return m

def diff_ci(cf,cq,kf,kq,rngseed):
    rng=random.Random(rngseed)
    cmf,cmq,kmf,kmq=by_item(cf),by_item(cq),by_item(kf),by_item(kq)
    cids=[i for i in cmf if i in cmq]; kids=[i for i in kmf if i in kmq]
    def delta(ci,ki):
        a=sum(cmf[i][0] for i in ci); an=sum(cmf[i][1] for i in ci); b=sum(cmq[i][0] for i in ci)
        c=sum(kmf[i][0] for i in ki); cn=sum(kmf[i][1] for i in ki); d=sum(kmq[i][0] for i in ki)
        return (a-b)/an-(c-d)/cn
    pt=delta(cids,kids); bs=[]
    for _ in range(B):
        cs=[cids[rng.randrange(len(cids))] for _ in cids]; ks=[kids[rng.randrange(len(kids))] for _ in kids]
        bs.append(delta(cs,ks))
    bs.sort(); return pt*100, bs[int(.025*B)]*100, bs[int(.975*B)]*100

# load all
data={m:{(s,p):load(s,m,p) for s in ["vFgrid_cult","vFgrid_ctrl"] for p in PREC} for m in MODELS}
M=[]; M.append("% AUTO-GENERATED by artifact/v2/build/gen_macros.py from the real test data.")
M.append("%% Reproduce: python build/gen_macros.py  (deterministic, seed %d). Do NOT edit by hand."%SEED)
def cmd(name,val): M.append("\\newcommand{\\%s}{%s}"%(name,val))
cmd("nArm","128"); cmd("nModels","3"); cmd("nRot","5"); cmd("nInst","640")
# midband stats
ms=json.load(open(V2/"data"/"midband_stats.json"))
for k,mc in [("N","regN"),("NE","regNE"),("CO","regCO"),("SE","regSE"),("S","regS")]:
    cmd(mc,str(ms["br_per_region"].get(k,0)))
for k,mc in [("sl16-30","bandA"),("sl31-50","bandB"),("sl51-80","bandC")]:
    cmd(mc,str(ms["br_per_bucket"].get(k,0)))
# calibration
cal=json.load(open(R/"wide_calibration_table.json"))["results"][0]["per_bucket_acc"]
for k,mc in [("sl0-1","CalibSLa"),("sl2-3","CalibSLb"),("sl4-7","CalibSLc"),("sl8-15","CalibSLd"),("sl16-30","CalibSLe"),("sl31-50","CalibSLf"),("sl51-80","CalibSLg")]:
    cmd(mc,"%.0f"%(cal[k][0]*100))
# per-model accuracy + rstd
PM={"fp16":"Fp","int8":"Int","nf4":"Nf"}
for mk in MODELS:
    sh=SHORT[mk]
    for p in PREC:
        cmd(f"{sh}Cult{PM[p]}","%.1f"%(acc(data[mk][("vFgrid_cult",p)])*100))
        cmd(f"{sh}Ctrl{PM[p]}","%.1f"%(acc(data[mk][("vFgrid_ctrl",p)])*100))
    cmd(f"{sh}RstdFp","%.3f"%rstd(data[mk][("vFgrid_cult","fp16")]))
    cmd(f"{sh}RstdNf","%.3f"%rstd(data[mk][("vFgrid_cult","nf4")]))
# per-model differential + CI ; pooled
import math
pooled={"int8":[],"nf4":[]}; halfwidths=[]
for qi,q in enumerate(["int8","nf4"]):
    for mi,mk in enumerate(MODELS):
        sh=SHORT[mk]
        pt,lo,hi=diff_ci(data[mk][("vFgrid_cult","fp16")],data[mk][("vFgrid_cult",q)],
                         data[mk][("vFgrid_ctrl","fp16")],data[mk][("vFgrid_ctrl",q)],SEED+qi*10+mi)
        QN={"int8":"Int","nf4":"Nf"}[q]
        cmd(f"{sh}Diff{QN}","%+.1f"%pt); cmd(f"{sh}Diff{QN}Lo","%+.1f"%lo); cmd(f"{sh}Diff{QN}Hi","%+.1f"%hi)
        pooled[q].append(pt); halfwidths.append((hi-lo)/2.0)
    cmd(f"PooledDiff{'Int' if q=='int8' else 'Nf'}","%+.1f"%(sum(pooled[q])/3))
cmd("mde","%d"%math.ceil(max(halfwidths)))

# ---- enrichment: per-band, per-region cultural erosion; int8 RStd ----
meta={}
for ln in open(V2/"grid_cult"/"cultural_strata.jsonl"):
    d=json.loads(ln); meta[d["id"]]=(d["rarity"]["band"], d.get("region","NA"))
def agg(prec):
    tot=defaultdict(lambda:[0,0]); reg=defaultdict(lambda:[0,0])
    for mk in MODELS:
        for r in data[mk][("vFgrid_cult",prec)]:
            b,rg=meta[r["id"]]; tot[b][0]+=r["correct"]; tot[b][1]+=1
            grp="NNE" if rg in ("N","NE") else ("SES" if rg in ("S","SE") else "CO")
            reg[grp][0]+=r["correct"]; reg[grp][1]+=1
    return tot,reg
FP=agg("fp16"); IT=agg("int8"); NF=agg("nf4")
bandmap={"sl16-30":"A","sl31-50":"B","sl51-80":"C"}
for b,tag in bandmap.items():
    fp=FP[0][b][0]/FP[0][b][1]*100; it=IT[0][b][0]/IT[0][b][1]*100; nf=NF[0][b][0]/NF[0][b][1]*100
    cmd(f"BandFp{tag}","%.0f"%fp); cmd(f"BandIntDrop{tag}","%+.1f"%(fp-it)); cmd(f"BandNfDrop{tag}","%+.1f"%(fp-nf))
    cmd(f"BandN{tag}",str(FP[0][b][1]//(5*len(MODELS))))
for grp,tag in [("NNE","NNE"),("SES","SES")]:
    fp=FP[1][grp][0]/FP[1][grp][1]*100; it=IT[1][grp][0]/IT[1][grp][1]*100; nf=NF[1][grp][0]/NF[1][grp][1]*100
    cmd(f"Reg{tag}IntDrop","%+.1f"%(fp-it)); cmd(f"Reg{tag}NfDrop","%+.1f"%(fp-nf)); cmd(f"Reg{tag}N",str(FP[1][grp][1]//(5*len(MODELS))))
for mk in MODELS:
    cmd(f"{SHORT[mk]}RstdInt","%.3f"%rstd(data[mk][("vFgrid_cult","int8")]))

OUT.write_text("\n".join(M)+"\n")
print("wrote",OUT)
print("\n".join(M))
